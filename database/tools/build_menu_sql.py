#!/usr/bin/env python3
"""
Generates database/migrations/002_menu_catalog.sql from backend/menu_catalog.py.

Run from the project root:   python3 tools/build_menu_sql.py

The generated SQL is idempotent and NEVER overwrites a price or availability
flag that someone already set in MySQL:
  * existing rows (matched by slug, or by their legacy name) get metadata only
  * missing rows are inserted
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "backend"))
from menu_catalog import CATALOG  # noqa: E402


def q(value):
    if value is None:
        return "NULL"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("\\", "\\\\").replace("'", "''") + "'"


out = [
    "-- =====================================================================",
    "-- Migration 002 - Menu catalogue (FOOD / SNACKS & BEVERAGES)",
    "-- GENERATED by tools/build_menu_sql.py from backend/menu_catalog.py",
    "-- Idempotent. Never overwrites price or is_available of existing rows.",
    "-- Requires migration 001.",
    "-- =====================================================================",
    "",
]

for n, it in enumerate(CATALOG, start=1):
    image_path = f"assets/images/menu/{it['slug']}.jpg"
    legacy = ", ".join(q(x) for x in it["legacy_names"] + [it["name"]])
    out.append(f"-- {it['name']}")
    # 1) adopt an existing row (old name) without touching price / availability
    out.append(
        "UPDATE menu_items SET "
        f"slug={q(it['slug'])}, name={q(it['name'])}, description={q(it['description'])}, "
        f"main_category={q(it['main_category'])}, category={q(it['category'])}, flavour={q(it['flavour'])}, "
        f"is_vegetarian={it['is_vegetarian']}, image_path={q(image_path)}, "
        f"prep_time_min={it['prep_time_min']}, prep_time_max={it['prep_time_max']}, sort_order={n * 10} "
        f"WHERE slug IS NULL AND name IN ({legacy}) ORDER BY id LIMIT 1;"
    )
    # 2) insert if still missing
    out.append(
        "INSERT INTO menu_items (slug, name, description, price, image_url, image_path, category, main_category, "
        "flavour, is_vegetarian, is_available, prep_time_min, prep_time_max, sort_order)\n"
        f"SELECT {q(it['slug'])}, {q(it['name'])}, {q(it['description'])}, {it['price']:.2f}, NULL, {q(image_path)}, "
        f"{q(it['category'])}, {q(it['main_category'])}, {q(it['flavour'])}, {it['is_vegetarian']}, 1, "
        f"{it['prep_time_min']}, {it['prep_time_max']}, {n * 10}\n"
        f"FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM menu_items WHERE slug={q(it['slug'])});"
    )
    out.append("")

dest = os.path.join(ROOT, "database", "migrations", "002_menu_catalog.sql")
with open(dest, "w", encoding="utf-8") as fh:
    fh.write("\n".join(out))
print(f"Wrote {dest} ({len(CATALOG)} items)")
